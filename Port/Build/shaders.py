"""Wrap the pinned original HLSL in Unity ShaderLab for desktop rendering.

Content identity remains the hash of the unmodified vertex/pixel source pair.
This is a build-time adapter, not a runtime compiler for arbitrary mod shaders.
"""
import hashlib
import re
import argparse
from pathlib import Path
import baseline as b


def generate(check=False):
    if (b.PORT / "source-lock.json").exists():
        import source_guard
        source_guard.check_upstream(b.SHA)
    else:
        b.check_upstream(b.SHA)
    destination = b.ROOT / "Assets/SCUnity/Resources/Shaders"
    destination.mkdir(parents=True, exist_ok=True)
    seen = set()
    for folder in ("Engine/Resources", "Survivalcraft/Content/Assets/Shaders"):
        for vertex in sorted((b.UPSTREAM / folder).glob("*.vsh")):
            pixel = vertex.with_suffix(".psh")
            vs, ps = (p.read_text(encoding="utf-8-sig") for p in (vertex, pixel))
            identity = hashlib.sha256((vs + "\n" + ps).encode()).hexdigest()[:16]
            if identity in seen:
                continue
            seen.add(identity)
            macros = set(re.findall(r"#\s*ifn?def\s+(\w+)", vs + ps)) - {"HLSL", "GLSL", "GL_ES"}
            lights = {"ONE_LIGHT", "TWO_LIGHTS", "THREE_LIGHTS"}
            pragmas = ["#pragma multi_compile _ " + name for name in sorted(macros - lights - {"USE_LIGHTING"})]
            if macros & lights:
                pragmas.append("#pragma multi_compile _ ONE_LIGHT TWO_LIGHTS THREE_LIGHTS")
                pragmas.append("#if defined(ONE_LIGHT) || defined(TWO_LIGHTS) || defined(THREE_LIGHTS)\n#define USE_LIGHTING\n#endif")
            vs = re.sub(r"\bvoid main\(", "void SCVert(", vs)
            ps = re.sub(r"\bvoid main\(", "void SCFrag(", ps)
            # Unity supplies these channels through Mesh.SetUVs; original Engine
            # semantics and its vertex buffers remain unchanged.
            vs = re.sub(r":\s*INSTANCE\b", ": TEXCOORD7", vs)
            vs = re.sub(r":\s*BLENDINDICES\b", ": TEXCOORD6", vs)
            vs = re.sub(r":\s*BLENDWEIGHTS\b", ": TEXCOORD5", vs)
            vs = re.sub(r"(sv_position\s*=.*?;)", r"\1\n#if UNITY_REVERSED_Z\nsv_position.z = sv_position.w - sv_position.z;\n#endif", vs)
            ps = re.sub(r"\bu_samplerState\b", "sampler_u_texture", ps)
            shader = '''// Generated by Port/Build/shaders.py from pinned original HLSL.
Shader "SCUnity/Port/IDENTITY" {
Properties { _Cull("Cull",Float)=0 _Src("Source",Float)=1 _Dst("Destination",Float)=0 _SrcA("Source alpha",Float)=1 _DstA("Destination alpha",Float)=0 _ZWrite("Depth write",Float)=0 _ZTest("Depth test",Float)=8 }
SubShader { Tags {"RenderPipeline"="UniversalPipeline"} Pass {
Cull [_Cull] Blend [_Src] [_Dst], [_SrcA] [_DstA] ZWrite [_ZWrite] ZTest [_ZTest]
HLSLPROGRAM
#pragma target 4.5
#pragma vertex SCVert
#pragma fragment SCFrag
PRAGMAS
#include "Packages/com.unity.render-pipelines.core/ShaderLibrary/Common.hlsl"
#define HLSL
#define MAX_INSTANCES_COUNT 64
#define MAX_JOINTS_COUNT 128
#if defined(SHADER_STAGE_VERTEX)
VERTEX
#endif
#if defined(SHADER_STAGE_FRAGMENT)
PIXEL
#endif
ENDHLSL
} }
}
'''.replace("IDENTITY", identity).replace("PRAGMAS", "\n".join(pragmas)).replace("VERTEX\n", vs + "\n").replace("PIXEL\n", ps + "\n")
            path = destination / (vertex.stem + "-" + identity + ".shader")
            text = "\n".join(line.rstrip() for line in shader.splitlines()) + "\n"
            if check:
                if not path.exists() or path.read_text(encoding="utf-8") != text:
                    raise ValueError("Generated shader differs: " + str(path))
            else:
                path.write_text(text, encoding="utf-8", newline="\n")
            meta = path.with_suffix(path.suffix + ".meta")
            if not meta.exists():
                if check:
                    raise ValueError("Missing shader metadata: " + str(meta))
                meta.write_text("fileFormatVersion: 2\nguid: " + hashlib.md5(("scunity-shader-" + identity).encode()).hexdigest() + "\n")
    return sorted(seen)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    print(generate(parser.parse_args().check))
